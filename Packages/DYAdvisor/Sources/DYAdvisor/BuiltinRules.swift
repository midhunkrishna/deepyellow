/// The built-in reclaim rules. Tiers, side conditions and exceptions follow the research notes (Part 1) and are never
/// upgraded to a safer tier than the evidence supports.
enum BuiltinRules {
    /// Every built-in rule.
    static var all: [ReclaimRule] { caches + developer + containers + packageManagers + personal }

    /// Shorthand constructor keeping the table below readable.
    private static func rule(_ id: String, _ title: String, _ pattern: String, _ tier: SafetyTier, is whatItIs: String,
                             loss consequence: String, note: String? = nil, run command: String? = nil,
