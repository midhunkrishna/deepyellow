        ReclaimRule(id: id, title: title, pattern: pattern, tier: tier, whatItIs: whatItIs, consequence: consequence,
                    sideCondition: note, cleanupCommand: command, ownerBundleIDs: owners, source: source)
    }

    private static let apple = "Apple developer documentation"
    private static let unverified = "Research notes (unverified)"

